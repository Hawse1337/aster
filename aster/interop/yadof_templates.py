"""Generate the yadof workspace files that route a study through our guarded solver.

The installed yadof v0.8.3 workspace defines three seams (verified against the package, not
guessed):

* ``job_template/parameters_constraints.py`` - ``PARAMETERS`` of ``Parameter(name, ((low, high),),
  unit=...)`` plus ``get_parameters()``;
* ``job_template/evaluation.py`` - ``create_evaluation_session(context)`` returning a session
  whose ``evaluate_rawdata(parameters, context)`` yields ``{filename: {array..., "metadata":
  json}}``; this is the simulator seam;
* ``submit/calc_cost.py`` - ``calculate_cost(sample_rawdata, raw_variables)`` returning one
  minimisation cost per objective.

``workflow.py`` stays as yadof generated it: it only calls the session and writes the npz files.
So we replace the evaluation session (and, when the objectives differ from the starter, the cost
policy) and leave the orchestration to yadof.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Sequence

__all__ = [
    "evaluation_source",
    "cost_source",
    "write_workspace_files",
    "OBJECTIVE_KINDS",
]

# the metrics yadof optimises by default, in the order of the response vector
OBJECTIVE_KINDS: tuple[str, ...] = ("s11_bandwidth", "peak_gain")
UNIT_BY_KIND = {"s11_bandwidth": "GHz", "peak_gain": "dBi", "radiation_efficiency": "1"}

_EVALUATION_TEMPLATE = '''"""Guarded-evaluation session for the yadof workspace.

Generated by ``aster.interop.yadof_templates.evaluation_source``. The session rebuilds the
geometry from the candidate parameters, runs one guarded HFSS solve and returns the metrics as
yadof raw data. Regenerate this file instead of editing it.
"""
from __future__ import annotations

import json

import numpy as np

CAMPAIGN_DIR = {campaign!r}
PROJECT = {project!r}
DESIGN = {design!r}
SETUP = {setup!r}
SWEEP = {sweep!r}
PID = {pid!r}
PORT = {port!r}
PASSES = {passes!r}
MAX_DELTA_S = {max_delta!r}
BAND_LOW = {band_low!r}
BAND_HIGH = {band_high!r}
SWEEP_STEP = {sweep_step!r}
MAX_MINUTES = {max_minutes!r}
CASE_MODULE = {case_module!r}
INCLUDE_EFFICIENCY = {include_efficiency!r}
OBJECTIVE_KINDS = {objective_kinds!r}
DATA_NAME = "response"
BRIDGE = None


class EvaluationSession:
    """One candidate per call; the session is reused across candidates of a generation."""

    def __init__(self, context=None):
        self.context = dict(context or {{}})
        self.bridge = None
        self.model = None

    # ------------------------------------------------------------------ internals
    def _connect(self):
        from aster.bridge import InProcessBridge

        if self.bridge is None:
            # a caller that already holds a connected bridge hands it over here; creating a
            # second one inside the session reached the broker without a target and asked for
            # a new AEDT session on port 0
            shared = globals().get("BRIDGE")
            if shared is not None:
                self.bridge = shared
                return self.bridge
            bridge = InProcessBridge()
            bridge.connect(pid=PID) if PID else bridge.connect(port=PORT)
            bridge.clear_stale_lock(PROJECT)
            self.bridge = bridge
            self._ensure_spec(bridge)
            self._ensure_sweep(bridge)
        return self.bridge

    def _ensure_spec(self, bridge):
        """Publish the design spec once; the guard refuses a submit without one."""
        import json as _json

        from importlib import import_module

        import os as _os

        if _os.path.isfile(_os.path.join(CAMPAIGN_DIR, "design_spec.json")):
            # the caller already published it; a second create_spec goes through the broker
            # without a target and ends up asking for a new AEDT session on port 0
            return
        module = import_module("aster.cases." + CASE_MODULE)
        spec = module.build_case(include_efficiency=INCLUDE_EFFICIENCY).to_spec()
        spec["frequency_ghz"] = [BAND_LOW, BAND_HIGH]
        spec.setdefault("evaluation", {{}})["frequencies_ghz"] = [BAND_HIGH - 2.0]
        spec.setdefault("execution_policy", {{}})["touchstone_retries"] = 40
        spec["execution_policy"]["touchstone_retry_delay_s"] = 15.0
        try:
            bridge.create_spec(CAMPAIGN_DIR, spec)
        except Exception:  # noqa: BLE001 - an existing spec is fine
            pass

    def _ensure_sweep(self, bridge):
        """Create the discrete band sweep once per session (same rule as the GUI runner).

        Without it the guard refuses the export as incomplete; doing it per candidate is what
        broke the earlier attempts, so it runs on the first connect only.
        """
        from aster.executor import setup_config_code

        code = setup_config_code(
            project_path=PROJECT,
            design_name=DESIGN,
            setup_name=SETUP,
            passes=int(PASSES),
            max_delta_s=float(MAX_DELTA_S),
            band_ghz=(BAND_LOW, BAND_HIGH),
            sweep_name=SWEEP,
            step_ghz=float(SWEEP_STEP),
        )
        try:
            bridge.execute_code(code, pid=PID or None)
        except Exception as exc:  # noqa: BLE001 - keep the reason, do not swallow it
            self.setup_error = "%s: %s" % (type(exc).__name__, str(exc)[:300])

    def _model(self):
        from importlib import import_module

        if self.model is None:
            self.model = import_module("aster.cases." + CASE_MODULE).build_model()
        return self.model

    def _case(self):
        from importlib import import_module

        module = import_module("aster.cases." + CASE_MODULE)
        return module.build_case(include_efficiency=INCLUDE_EFFICIENCY)

    # ------------------------------------------------------------------ yadof API
    def evaluate_rawdata(self, parameters, context=None):
        """One candidate, with one reconnect if the worker session got poisoned.

        A failed PyAEDT command (an InsertFrequencySweep on a project that already carries the
        sweep, a CreateReport that comes back as a draft) leaves the broker's session unusable:
        every later call in that worker comes back as 'Failed to start new AEDT gRPC session on
        port 0'. Dropping the bridge and reconnecting recovers, so the retry is worth the cost.
        """
        try:
            return self._evaluate_once(parameters, context)
        except Exception as exc:  # noqa: BLE001 - one reconnect, then report
            self.setup_error = "%s: %s" % (type(exc).__name__, str(exc)[:200])
            self.bridge = None
            try:
                return self._evaluate_once(parameters, context)
            except Exception as second:  # noqa: BLE001
                self.setup_error = "%s: %s" % (type(second).__name__,
                                               str(second)[:200])
                return self._error_payload(str(second)[:300])

    def _evaluate_once(self, parameters, context=None):
        from aster.apply import ModelApplier
        from aster.executor import GuardConfig, GuardExecutor

        bridge = self._connect()
        model = self._model()
        space = model.space
        params = dict(space.default())
        for key, value in dict(parameters).items():
            if key in params:
                params[key] = value
        params = space.validate(params)

        applier = ModelApplier(model, bridge, project_path=PROJECT, design_name=DESIGN,
                               pid=PID, incremental=True)
        applied = applier.apply(params)
        if not applied.ok:
            return self._error_payload(applied.error or "apply failed")

        # deliberately no sweep reconfiguration here. Rebuilding the sweep on a project that
        # already carries one raises InsertFrequencySweep and leaves the session on a partially
        # solved sweep (observed as a 1 GHz band against the batch arm's 3 GHz). The export side
        # now waits for the sweep to finish, which is the failure the refresh was meant to fix.

        config = GuardConfig(
            campaign_dir=CAMPAIGN_DIR,
            project_name=PROJECT.rsplit("\\\\", 1)[-1].rsplit("/", 1)[-1].replace(".aedt", ""),
            design_name=DESIGN,
            setup_name=SETUP,
            # far fields come from the same setup; naming it stops the export from inheriting
            # the S11 sweep and failing at CreateReport
            farfield_setup_name=SETUP,
            sweep_name=SWEEP,
            pid=PID or None,
            port=None if PID else PORT,
            num_cores=16,
            poll_interval_s=10.0,
            timeout_s=float(MAX_MINUTES) * 60.0,
        )
        case = self._case()
        executor = GuardExecutor(case, config, bridge=bridge)
        entry = executor.evaluate(case.make_candidate(params, algorithm="yadof"))
        values = [entry.metrics.get(kind) for kind in OBJECTIVE_KINDS]
        if any(value is None for value in values) or entry.status != "COMPLETED":
            return self._error_payload(entry.status)
        metadata = {{
            "schema_version": 1,
            "rawdata_name": DATA_NAME,
            "shape": [len(values)],
            "names": list(OBJECTIVE_KINDS),
            "units": {units!r},
            "feasible": bool(entry.feasible),
            "violation": float(entry.total_violation),
            "run_id": entry.run_id,
            "setup_error": getattr(self, "setup_error", None),
        }}
        return {{DATA_NAME + ".npz": {{
            "values": np.asarray(values, dtype=float),
            "metadata": json.dumps(metadata, sort_keys=True),
        }}}}

    def _error_payload(self, reason):
        metadata = {{"schema_version": 1, "rawdata_name": DATA_NAME, "shape": [0],
                     "error": str(reason)[:400], "names": list(OBJECTIVE_KINDS)}}
        return {{DATA_NAME + ".npz": {{
            "values": np.asarray([], dtype=float),
            "metadata": json.dumps(metadata, sort_keys=True),
        }}}}

    def close(self):
        self.bridge = None


def create_evaluation_session(context):
    return EvaluationSession(context)
'''

_COST_TEMPLATE = '''"""Map our metrics to yadof's minimisation costs.

Generated by ``aster.interop.yadof_templates.cost_source``. yadof minimises, so a metric we
want to maximise enters as its negative; an empty or non-finite response is an error sample and
receives ``ERROR_COST``.
"""
from __future__ import annotations

from collections.abc import Sequence

import numpy as np

from yadof.job_template.cost_misc import calculate_rawdata_cost
from yadof.job_template.rawdata_contract import RawDataItem, RawDataView

OBJECTIVE_KINDS = {objective_kinds!r}
OBJECTIVE_NAMES = tuple("cost_" + kind for kind in OBJECTIVE_KINDS)
MAXIMISE = {maximise!r}
ERROR_COST = 1.0


def _calculate_loaded_cost(loaded_items: Sequence[RawDataView], raw_variables: object | None):
    del raw_variables
    view = next(view for view in loaded_items if view.name == "response")
    values = np.asarray(view.data, dtype=float).ravel()
    if values.shape != (len(OBJECTIVE_KINDS),) or not np.all(np.isfinite(values)):
        return tuple(ERROR_COST for _ in OBJECTIVE_KINDS)
    costs = []
    for index, kind in enumerate(OBJECTIVE_KINDS):
        value = float(values[index])
        costs.append(-value if kind in MAXIMISE else value)
    return tuple(costs)


def calculate_cost(sample_rawdata: Sequence[RawDataItem], raw_variables: object | None = None):
    return calculate_rawdata_cost(
        sample_rawdata,
        raw_variables,
        objective_names=OBJECTIVE_NAMES,
        calculate_loaded_cost=_calculate_loaded_cost,
        error_cost=ERROR_COST,
    )


def get_objective_names() -> tuple[str, ...]:
    return OBJECTIVE_NAMES
'''


def evaluation_source(
    *,
    campaign_dir: str,
    project: str,
    design: str = "f24g05",
    setup: str = "P4",
    sweep: str = "ANT_Band",
    pid: int | None = None,
    port: int | None = None,
    passes: int = 8,
    max_delta_s: float = 0.02,
    max_minutes: int = 50,
    band_ghz: Sequence[float] = (24.0, 30.0),
    sweep_step_ghz: float = 1.0,
    case_module: str = "lens28_var",
    include_efficiency: bool = False,
    objective_kinds: Sequence[str] | None = None,
) -> str:
    """Render ``job_template/evaluation.py`` for our guarded solver."""
    if pid is None and port is None:
        raise ValueError("pass either pid or port so the session can reach AEDT")
    if not campaign_dir or not project:
        raise ValueError("campaign_dir and project are required")
    kinds = tuple(objective_kinds or OBJECTIVE_KINDS)
    if include_efficiency and "radiation_efficiency" not in kinds:
        kinds = kinds + ("radiation_efficiency",)
    units = {kind: UNIT_BY_KIND.get(kind, "") for kind in kinds}
    return _EVALUATION_TEMPLATE.format(
        campaign=campaign_dir,
        project=project,
        design=design,
        setup=setup,
        sweep=sweep,
        pid=pid,
        port=port,
        passes=int(passes),
        max_delta=float(max_delta_s),
        band_low=float(band_ghz[0]),
        band_high=float(band_ghz[1]),
        sweep_step=float(sweep_step_ghz),
        max_minutes=int(max_minutes),
        case_module=case_module,
        include_efficiency=bool(include_efficiency),
        objective_kinds=kinds,
        units=units,
    )


def cost_source(objective_kinds: Sequence[str] | None = None,
                maximise: Sequence[str] | None = None) -> str:
    """Render ``submit/calc_cost.py`` for the same objectives."""
    kinds = tuple(objective_kinds or OBJECTIVE_KINDS)
    maximised = tuple(maximise if maximise is not None else kinds)
    return _COST_TEMPLATE.format(objective_kinds=kinds, maximise=maximised)


def write_workspace_files(
    workspace: str | Path,
    **kwargs: Any,
) -> dict[str, str]:
    """Write both generated files into an initialised yadof workspace."""
    root = Path(workspace)
    if not (root / "job_template").is_dir():
        raise ValueError("not a yadof workspace: %s" % root)
    kinds = kwargs.pop("objective_kinds", None)
    maximise = kwargs.pop("maximise", None)
    targets = {
        "evaluation": root / "job_template" / "evaluation.py",
        "cost": root / "submit" / "calc_cost.py",
    }
    targets["evaluation"].write_text(evaluation_source(objective_kinds=kinds, **kwargs),
                                     encoding="utf-8")
    (root / "submit").mkdir(parents=True, exist_ok=True)
    targets["cost"].write_text(cost_source(kinds, maximise), encoding="utf-8")
    return {name: str(path) for name, path in targets.items()}
